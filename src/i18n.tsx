const dictionaries = { cs, en };

const STORAGE_KEY = 'fakturagen:language';

function detectLanguage(): Language {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'cs' || saved === 'en') return saved;
  } catch { /* ignore unavailable storage */ }
  const systemLanguage = navigator.languages?.[0] ?? navigator.language ?? 'en';
  return systemLanguage.toLowerCase().startsWith('cs') ? 'cs' : 'en';
}

export function translate(language: Language, key: TranslationKey, params?: Record<string, string | number>) {
  let value: string = dictionaries[language][key] ?? dictionaries.cs[key];
  if (params) {
    for (const [name, replacement] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

interface I18nContextValue {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(detectLanguage);
  const locale = language === 'cs' ? 'cs-CZ' : 'en-GB';

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      localStorage.setItem(STORAGE_KEY, language);
    } catch { /* ignore unavailable storage */ }
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale,
    setLanguage: setLanguageState,
    t: (key, params) => translate(language, key, params),
  }), [language, locale]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error('useI18n must be used inside I18nProvider.');
  return context;
}
